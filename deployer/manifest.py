"""Pure: registered model + version + artifact URI -> InferenceService manifest text. No I/O.

Deterministic on purpose: the same input must give the same bytes, otherwise every deployer round
sees a difference, commits, and the pod rolls. Nothing time-dependent goes in here; KServe copies
ISVC annotations/labels onto the pod template, so every field below changes the pod when it changes.
"""
from __future__ import annotations

import yaml

HEADER = ("# GENERATED by the deployer (python -m deployer). Do not edit by hand:\n"
          "# change the @production alias in MLflow and the deployer rewrites this file.\n")


def kube_name(registered_model: str) -> str:
    return registered_model.replace("_", "-")


def manifest_path(registered_model: str) -> str:
    return f"serving/k8s/30-isvc-{kube_name(registered_model)}.yaml"


def build_isvc(registered_model: str, version: str, storage_uri: str, namespace: str = "serving") -> str:
    doc = {
        "apiVersion": "serving.kserve.io/v1beta1",
        "kind": "InferenceService",
        "metadata": {
            "name": kube_name(registered_model),
            "namespace": namespace,
            "labels": {"mlops/registered-model": registered_model},
            "annotations": {"mlops/model-version": str(version)},
        },
        "spec": {"predictor": {
            "serviceAccountName": "model-puller",
            "model": {
                "modelFormat": {"name": "mlflow", "version": "3"},
                "runtime": "mlflow-mlserver",
                "protocolVersion": "v2",
                "storageUri": storage_uri,
            },
        }},
    }
    return HEADER + yaml.safe_dump(doc, sort_keys=False)
